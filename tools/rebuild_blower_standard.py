def rows(values_by_ratio, stages=None):
    return [
        {"b2_d2": ratio, "stages": stages, "eff": values}
        for ratio, values in zip(RATIOS, values_by_ratio)
    ]


def multi(values_by_stage):
    out = []
    for stage, stage_rows in values_by_stage:
        out.extend(rows(stage_rows, stage))
    return out


